"""
Extract Session Transcripts

Reads Claude Code session JSONL files from ~/.claude/projects/*/ and
~/.claude/projects-archive/*/ (listed directly; sessions-index.json is naming
metadata only, because Claude Code stopped maintaining it) and outputs filtered markdown transcripts to:
  <agent home>/transcripts/  (resolved by agent_paths.py)

What is extracted:
  - User prompts (full text)
  - Assistant text responses (no tool JSON)
  - Tool breadcrumbs (file paths for Read/Edit/Write; counts for Bash)

What is dropped:
  - Tool call parameters and results
  - System prompts / <system-reminder> blocks
  - Thinking/reasoning blocks
  - Base64 / binary content
  - Compaction summaries
  - Subagent messages (isSidechain: true)

Usage:
    python3 extract_session_transcripts.py                          # All sessions, skip up-to-date
    python3 extract_session_transcripts.py --days 7                 # Only sessions from last 7 days
    python3 extract_session_transcripts.py --project /path/to/proj  # Single project
    python3 extract_session_transcripts.py --session-id <uuid>      # Single session
    python3 extract_session_transcripts.py --force                  # Re-extract everything
    python3 extract_session_transcripts.py --verbose                # Verbose output
"""

