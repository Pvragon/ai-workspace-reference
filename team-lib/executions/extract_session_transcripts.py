def process_session(jsonl_path: Path, entry: dict, verbose: bool = False) -> Optional[dict]:
    """
    Stream-process a session JSONL file and return transcript data.

    Returns:
        dict with keys: frontmatter, body, filename, session_id
        None if the session has no meaningful content.
    """
    session_id = entry.get("sessionId", "")
    created = entry.get("created", "")
    project_path = entry.get("projectPath", "")
    project_name = os.path.basename(project_path) if project_path else "unknown"
    message_count_est = entry.get("messageCount", 0)

    # Metadata we'll collect
    first_timestamp: Optional[float] = None
    last_timestamp: Optional[float] = None
    tools_used: set[str] = set()
    files_touched: list[str] = []
    files_touched_set: set[str] = set()
    actual_message_count = 0

    # Body accumulation
    body_lines: list[str] = []

    # State machine
    prev_timestamp: Optional[float] = None
    pending_tool_calls: list[dict] = []  # tools accumulated after last assistant text

    def _flush_breadcrumb():
        """If there are pending tool calls, emit the breadcrumb."""
        nonlocal pending_tool_calls
        if pending_tool_calls:
            bc = _build_breadcrumb(pending_tool_calls)
            if bc:
                body_lines.append("")
                body_lines.append(bc)
            pending_tool_calls = []

    def _parse_ts(ts_val) -> Optional[float]:
        """Parse a timestamp (ISO string or ms-int) to POSIX seconds."""
        if ts_val is None:
            return None
        if isinstance(ts_val, str):
            try:
                dt = datetime.fromisoformat(ts_val.replace("Z", "+00:00"))
                return dt.timestamp()
            except (ValueError, OSError):
                return None
        if isinstance(ts_val, (int, float)):
            # Could be milliseconds or seconds
            if ts_val > 1e10:
                return ts_val / 1000.0
            return float(ts_val)
        return None

    line_num = 0
    try:
        with open(jsonl_path, "r", encoding="utf-8", errors="replace") as f:
            for raw_line in f:
                line_num += 1
                raw_line = raw_line.strip()
                if not raw_line:
                    continue
                try:
                    obj = json.loads(raw_line)
                except json.JSONDecodeError:
                    if verbose:
                        print(f"  WARN: malformed JSON at line {line_num} in {jsonl_path.name}", file=sys.stderr)
                    continue

                # Skip subagent messages
                if obj.get("isSidechain", False):
                    continue

                obj_type = obj.get("type", "")

                # Skip non-message types (custom-title, file-history-snapshot, summary, etc.)
                if obj_type not in ("user", "assistant"):
                    continue

                # Parse timestamp
                ts_raw = obj.get("timestamp") or obj.get("createdAt")
                ts = _parse_ts(ts_raw)

                if ts is not None:
                    if first_timestamp is None:
                        first_timestamp = ts
                    last_timestamp = ts

                    # Resume detection: gap > 1 hour
                    if prev_timestamp is not None and (ts - prev_timestamp) > RESUME_GAP_SECONDS:
                        dt_resume = datetime.fromtimestamp(ts).strftime("%Y-%m-%d")
                        body_lines.append("")
                        body_lines.append("---")
                        body_lines.append(f"[Session resumed {dt_resume}]")
                        body_lines.append("---")
                        body_lines.append("")
                    prev_timestamp = ts

                msg = obj.get("message", {})
                if not isinstance(msg, dict):
                    # Sometimes message is a string — treat as user text
                    if obj_type == "user" and isinstance(msg, str) and msg.strip():
                        if not _is_system_content(msg):
                            _flush_breadcrumb()
                            body_lines.append("")
                            body_lines.append(f"**the operator:** {msg.strip()}")
                            actual_message_count += 1
                    continue

                if obj_type == "user":
                    text = _extract_user_text(msg)
                    if text:
                        _flush_breadcrumb()
                        body_lines.append("")
                        body_lines.append(f"**the operator:** {text}")
                        actual_message_count += 1

                elif obj_type == "assistant":
                    text, tool_calls = _extract_assistant_content(msg)

                    # Emit any previous pending tool calls (from prior assistant turn with no text)
                    # Actually, flush happens before user messages. Here we handle consecutive
                    # assistant turns (rare but possible with tool_use pattern):
                    # Tool calls accumulate until the next user message.

                    if text:
                        body_lines.append("")
                        body_lines.append(f"**{AGENT_LABEL}:** {text}")
                        actual_message_count += 1

                    # Accumulate tool calls for breadcrumb (emitted before next user message)
                    for tc in tool_calls:
                        tool_name = tc.get("name", "")
                        if tool_name:
                            tools_used.add(tool_name)
                            # Track files touched
                            inp = tc.get("input", {}) or {}
                            for key in ("file_path", "notebook_path"):
                                fp = inp.get(key, "")
                                if fp and fp not in files_touched_set:
                                    files_touched_set.add(fp)
                                    files_touched.append(fp)
                        pending_tool_calls.append(tc)

    except OSError as e:
        print(f"  ERROR reading {jsonl_path}: {e}", file=sys.stderr)
        return None

    # Flush any trailing tool calls
    _flush_breadcrumb()

    # Must have some content
    if actual_message_count == 0:
        if verbose:
            print(f"  SKIP (no content): {session_id[:12]}", file=sys.stderr)
        return None

    # --- Build frontmatter ---
    duration_str = "unknown"
    if first_timestamp is not None and last_timestamp is not None:
        dur = last_timestamp - first_timestamp
        duration_str = _format_duration(dur)

    # Parse date from created (or first_timestamp)
    try:
        if created:
            date_dt = datetime.fromisoformat(created.replace("Z", "+00:00")).astimezone()
        elif first_timestamp:
            date_dt = datetime.fromtimestamp(first_timestamp)
        else:
            date_dt = datetime.now()
        date_str = date_dt.strftime("%Y-%m-%d")
    except (ValueError, OSError):
        date_str = "unknown"

    session_name = (entry.get("summary") or "").strip() or session_id[:8]

    frontmatter_lines = [
        "---",
        f"session_id: {session_id}",
        f"date: {date_str}",
        f'name: "{session_name}"',
        f"project: {project_name}",
        f'duration_estimate: "{duration_str}"',
        "topics: []",
        f"tools_used: [{', '.join(sorted(tools_used))}]",
        "files_touched:",
    ]
    if files_touched:
        for fp in files_touched[:30]:  # cap at 30 files
            frontmatter_lines.append(f"  - {fp}")
    else:
        frontmatter_lines.append("  []")
    frontmatter_lines.append(f"message_count: {actual_message_count}")
    frontmatter_lines.append("---")

    # --- Build header ---
    header_lines = [
        "",
        f"# {session_name}",
        f"**{date_str}** | {project_name} | ~{duration_str}",
        "",
        "---",
    ]

    # Remove leading blank lines from body
    while body_lines and not body_lines[0].strip():
        body_lines.pop(0)

    full_content = (
        "\n".join(frontmatter_lines)
        + "\n"
        + "\n".join(header_lines)
        + "\n"
        + "\n".join(body_lines)
        + "\n"
    )

    filename = _derive_filename(entry)

    return {
        "filename": filename,
        "content": full_content,
        "session_id": session_id,
        "session_name": session_name,
        "date": date_str,
        "project": project_name,
        "actual_message_count": actual_message_count,
    }


