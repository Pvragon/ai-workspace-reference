    print(f"  Errors:             {stats['errors']}")
    if stats["total_input_bytes"]:
        ratio = stats["total_output_bytes"] / stats["total_input_bytes"] * 100
        print(f"  Input:  {stats['total_input_bytes']:,} bytes")
        print(f"  Output: {stats['total_output_bytes']:,} bytes ({ratio:.1f}% of input)")
    print(f"\nTranscripts: {OUTPUT_DIR}")
