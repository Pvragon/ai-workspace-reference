# --- Paths ---
CLAUDE_PROJECTS_DIR = Path.home() / ".claude" / "projects"
OUTPUT_DIR = Path.home() / "ai-workspace" / "agents" / "your-agent" / "transcripts"
INDEX_FILE = OUTPUT_DIR / "TRANSCRIPT-INDEX.md"

# Resume gap threshold in seconds (1 hour)
RESUME_GAP_SECONDS = 3600

# Pattern to detect system/caveat injections in user messages
_SYSTEM_CONTENT_PATTERNS = [
    re.compile(r"<local-command-caveat>", re.IGNORECASE),
    re.compile(r"<system-reminder>", re.IGNORECASE),
    re.compile(r"^Caveat: The messages below were generated by the user while running local commands", re.MULTILINE),
    re.compile(r"<command-name>/clear</command-name>", re.IGNORECASE),
]

# Pattern for YYMMDD prefix
_YYMMDD_RE = re.compile(r"^\d{6}")


# ---------------------------------------------------------------------------
# Naming helpers
# ---------------------------------------------------------------------------

def _slugify(text: str) -> str:
    """Convert text to a filesystem-safe slug."""
    text = text.lower().strip()
    text = re.sub(r"[^\w\s-]", "", text)
    text = re.sub(r"[\s_]+", "-", text)
    text = re.sub(r"-+", "-", text)
    return text.strip("-")[:80]


def _derive_filename(entry: dict) -> str:
    """
    Derive the output filename for a session according to the naming rule:

    1. If summary was explicitly set (/rename) and already has YYMMDD prefix → use as-is.
    2. If summary was explicitly set but no YYMMDD prefix → prepend session-start date.
    3. If not renamed (summary == firstPrompt or truncation) → YYMMDD-HHMM-<first-3-words>.md
    """
    summary = (entry.get("summary") or "").strip()
    first_prompt = (entry.get("firstPrompt") or "").strip()
    created = entry.get("created", "")

    # Parse session start date
    try:
        dt = datetime.fromisoformat(created.replace("Z", "+00:00"))
        # Convert to local time
        local_dt = dt.astimezone()
        date_prefix = local_dt.strftime("%y%m%d")
        time_prefix = local_dt.strftime("%H%M")
    except (ValueError, OSError):
        date_prefix = "000000"
        time_prefix = "0000"

    # Detect if summary is a renamed (deliberate) title or just a truncated firstPrompt.
    # If summary starts with the same ~30 chars as firstPrompt, treat as NOT renamed.
    is_renamed = bool(summary) and not (
        summary[:30] == first_prompt[:30] or
        (first_prompt and first_prompt.startswith(summary))
    )

    if is_renamed:
        slug = _slugify(summary)
        if _YYMMDD_RE.match(slug):
            # Already has date prefix — use as-is
            return f"{slug}.md"
        else:
            return f"{date_prefix}-{slug}.md"
    else:
        # Fallback: YYMMDD-HHMM-<first-3-words>
        words = re.split(r"\s+", re.sub(r"[^\w\s]", " ", first_prompt.lower()).strip())
        word_slug = "-".join(w for w in words[:3] if w)[:40]
        if not word_slug:
            word_slug = entry.get("sessionId", "unknown")[:8]
        return f"{date_prefix}-{time_prefix}-{word_slug}.md"


# ---------------------------------------------------------------------------
# Duration formatting
# ---------------------------------------------------------------------------

def _format_duration(seconds: float) -> str:
    """Format seconds into a human-readable duration string."""
    if seconds < 60:
        return f"{int(seconds)}s"
    elif seconds < 3600:
        mins = int(seconds // 60)
        return f"{mins}m"
    else:
        hours = int(seconds // 3600)
        mins = int((seconds % 3600) // 60)
        if mins:
            return f"{hours}h {mins}m"
        return f"{hours}h"


