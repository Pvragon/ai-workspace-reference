def load_sessions_index(project_dir: Path) -> list[dict]:
    """Load sessions-index.json from a project directory. Returns list of entries."""
    idx_path = project_dir / "sessions-index.json"
    if not idx_path.exists():
        return []
    try:
        with open(idx_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, dict):
            return data.get("entries", [])
        if isinstance(data, list):
            return data
    except (json.JSONDecodeError, OSError) as e:
        print(f"  WARN: could not load {idx_path}: {e}", file=sys.stderr)
    return []


def run(
    days: Optional[int] = None,
    project: Optional[str] = None,
    session_id: Optional[str] = None,
    force: bool = False,
    verbose: bool = False,
) -> dict:
    """
    Main extraction runner. Returns summary stats dict.

    Args:
        days: Only process sessions from the last N days.
        project: Limit to a specific project path (basename or full path).
        session_id: Limit to a single session ID.
        force: Re-extract even if transcript is up-to-date.
        verbose: Print detailed progress.
    """
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # Collect all project dirs
    project_dirs = sorted(CLAUDE_PROJECTS_DIR.glob("*/"))

    # Filter to a specific project if requested
    if project:
        proj_basename = os.path.basename(project.rstrip("/"))
        project_dirs = [
            p for p in project_dirs
            if p.name == proj_basename or p.name.endswith(proj_basename.replace("/", "-"))
        ]
        if not project_dirs:
            # Try to match by contained project path
            project_dirs = [
                p for p in sorted(CLAUDE_PROJECTS_DIR.glob("*/"))
                if project.rstrip("/").replace("/", "-").lstrip("-") in p.name
            ]

    # Cutoff date for --days filter
    cutoff: Optional[datetime] = None
    if days:
        cutoff = datetime.now(timezone.utc) - timedelta(days=days)

    stats = {
        "processed": 0,
        "skipped_uptodate": 0,
        "skipped_no_content": 0,
        "errors": 0,
        "total_input_bytes": 0,
        "total_output_bytes": 0,
    }

    for proj_dir in project_dirs:
        if verbose:
            print(f"\nProject dir: {proj_dir.name}")

        entries = load_sessions_index(proj_dir)
        if not entries:
            # Fallback: enumerate JSONL files without index
            jsonl_files = [f for f in proj_dir.glob("*.jsonl") if not f.name.startswith("agent-")]
            entries = [
                {
                    "sessionId": f.stem,
                    "fullPath": str(f),
                    "firstPrompt": "",
                    "summary": "",
                    "created": "",
                    "projectPath": str(proj_dir),
                }
                for f in jsonl_files
            ]

        for entry in entries:
            sid = entry.get("sessionId", "")

            # Filter by session_id
            if session_id and sid != session_id:
                continue

            # Filter sidechains at index level
            if entry.get("isSidechain", False):
                continue

            # Filter by date
            if cutoff:
                created_str = entry.get("created", "")
                if created_str:
                    try:
                        created_dt = datetime.fromisoformat(created_str.replace("Z", "+00:00"))
                        if created_dt < cutoff:
                            continue
                    except (ValueError, OSError):
                        pass

            # Resolve JSONL path
            jsonl_path_str = entry.get("fullPath", "")
            if jsonl_path_str:
                jsonl_path = Path(jsonl_path_str)
            else:
                jsonl_path = proj_dir / f"{sid}.jsonl"

            if not jsonl_path.exists():
                if verbose:
                    print(f"  SKIP (missing): {sid[:12]}", file=sys.stderr)
                continue

            jsonl_mtime = jsonl_path.stat().st_mtime
            input_size = jsonl_path.stat().st_size

            # Determine expected output filename (estimate only — need entry data)
            # We'll check idempotency after computing the filename
            expected_name = _derive_filename(entry)
            out_path = OUTPUT_DIR / expected_name

            # Idempotency check: skip if transcript is newer than JSONL
            if not force and out_path.exists():
                transcript_mtime = out_path.stat().st_mtime
                if transcript_mtime >= jsonl_mtime:
                    stats["skipped_uptodate"] += 1
                    if verbose:
                        print(f"  SKIP (up-to-date): {expected_name}")
                    continue

            if verbose:
                print(f"  Processing: {sid[:12]}... ({input_size:,} bytes)")

            result = process_session(jsonl_path, entry, verbose=verbose)
            if result is None:
                stats["skipped_no_content"] += 1
                continue

            # Write output
            final_out_path = OUTPUT_DIR / result["filename"]
            try:
                with open(final_out_path, "w", encoding="utf-8") as f:
                    f.write(result["content"])
                output_size = final_out_path.stat().st_size
                stats["processed"] += 1
                stats["total_input_bytes"] += input_size
                stats["total_output_bytes"] += output_size
                if verbose:
                    ratio = output_size / input_size * 100 if input_size else 0
                    print(f"  WROTE: {result['filename']} ({output_size:,} bytes, {ratio:.1f}% of input)")
            except OSError as e:
                print(f"  ERROR writing {final_out_path}: {e}", file=sys.stderr)
                stats["errors"] += 1

    # Rebuild index
    _rebuild_index(OUTPUT_DIR, INDEX_FILE)

    return stats


