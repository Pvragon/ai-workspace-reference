if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Extract Claude Code session JSONL files into filtered markdown transcripts"
    )
    parser.add_argument(
        "--days",
        type=int,
        metavar="N",
        help="Only process sessions from the last N days",
    )
    parser.add_argument(
        "--project",
        type=str,
        metavar="PATH",
        help="Limit to sessions from a specific project path",
    )
    parser.add_argument(
        "--session-id",
        type=str,
        metavar="UUID",
        help="Process a single session by ID",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Re-extract even if transcripts are already up-to-date",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Print detailed progress to stdout",
    )
    args = parser.parse_args()

    stats = run(
        days=args.days,
        project=args.project,
        session_id=args.session_id,
        force=args.force,
        verbose=args.verbose,
    )

    print(f"\nDone.")
    print(f"  Processed:          {stats['processed']}")
    print(f"  Skipped (current):  {stats['skipped_uptodate']}")
    print(f"  Skipped (no content): {stats['skipped_no_content']}")
    print(f"  Renamed:            {stats['renamed']}")
    print(f"  Errors:             {stats['errors']}")
    print(f"  Missing:            {len(stats['missing'])}")
    for sid in stats["missing"][:20]:
        print(f"    MISSING transcript: {sid}")
    if stats["total_input_bytes"]:
        ratio = stats["total_output_bytes"] / stats["total_input_bytes"] * 100
        print(f"  Input:  {stats['total_input_bytes']:,} bytes")
        print(f"  Output: {stats['total_output_bytes']:,} bytes ({ratio:.1f}% of input)")
    print(f"\nTranscripts: {OUTPUT_DIR}")
    print(f"Index:       {INDEX_FILE}")
    if stats["errors"] or stats["missing"]:
        print("\nFAIL: not every session has a transcript.", file=sys.stderr)
        # A cron log nobody reads is not loud. Route it to the findings inbox (statusline
        # counter, escalates on age, resolves itself once a run stops re-recording it).
        # Best-effort: a findings failure must not mask the exit code.
        try:
            import subprocess
            subprocess.run(
                [sys.executable, str(Path(__file__).resolve().parent / "findings.py"), "record",
                 "--source", "extract_session_transcripts", "--key", "coverage",
                 "--text", f"{len(stats['missing'])} session(s) without a transcript, "
                           f"{stats['errors']} error(s); see my-lib/runtime/logs/session_transcripts.log"],
                timeout=30, capture_output=True)
        except Exception:
            pass
        sys.exit(1)
