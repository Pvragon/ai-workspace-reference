def _load_index_entries(index_path: Path) -> dict[str, dict]:
    """Load existing TRANSCRIPT-INDEX.md into a map of filename -> entry."""
    result: dict[str, dict] = {}
    if not index_path.exists():
        return result
    # Parse the markdown table
    with open(index_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line.startswith("|") or line.startswith("| Date"):
                continue
            cols = [c.strip() for c in line.split("|") if c.strip()]
            if len(cols) >= 4:
                date, session, project, file_ref = cols[0], cols[1], cols[2], cols[3]
                filename = file_ref.strip("`")
                result[filename] = {"date": date, "session": session, "project": project}
    return result


def _rebuild_index(output_dir: Path, index_path: Path) -> None:
    """Rebuild TRANSCRIPT-INDEX.md from all transcript files in output_dir."""
    transcripts = sorted(output_dir.glob("*.md"))
    transcripts = [t for t in transcripts if t.name != "TRANSCRIPT-INDEX.md"]

    rows: list[tuple[str, str, str, str]] = []  # (date, session, project, filename)

    for t in transcripts:
        # Parse frontmatter for metadata
        date_val = ""
        session_val = t.stem
        project_val = ""
        with open(t, "r", encoding="utf-8") as f:
            in_fm = False
            for line in f:
                line = line.rstrip()
                if line == "---":
                    if not in_fm:
                        in_fm = True
                        continue
                    else:
                        break
                if in_fm:
                    if line.startswith("date:"):
                        date_val = line.split(":", 1)[1].strip()
                    elif line.startswith("name:"):
                        session_val = line.split(":", 1)[1].strip().strip('"')
                    elif line.startswith("project:"):
                        project_val = line.split(":", 1)[1].strip()
        rows.append((date_val, session_val, project_val, t.name))

    # Sort by date desc
    rows.sort(key=lambda r: r[0], reverse=True)

    lines = [
        "# Transcript Index",
        "",
        "| Date | Session | Project | File |",
        "|------|---------|---------|------|",
    ]
    for date_val, session_val, project_val, filename in rows:
        # Truncate long session names in index (full name is in the file's frontmatter)
        display_name = session_val if len(session_val) <= 60 else session_val[:57] + "..."
        lines.append(f"| {date_val} | {display_name} | {project_val} | `{filename}` |")

    lines.append("")
    lines.append(f"*{len(rows)} transcript{'s' if len(rows) != 1 else ''} total*")
    lines.append("")

    with open(index_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


