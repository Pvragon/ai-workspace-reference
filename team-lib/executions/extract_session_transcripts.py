def load_sessions_index(project_dir: Path) -> list[dict]:
    """Load sessions-index.json from a project directory. Returns list of entries."""
    idx_path = project_dir / "sessions-index.json"
    if not idx_path.exists():
        return []
    try:
        with open(idx_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, dict):
            return data.get("entries", [])
        if isinstance(data, list):
            return data
    except (json.JSONDecodeError, OSError) as e:
        print(f"  WARN: could not load {idx_path}: {e}", file=sys.stderr)
    return []


def _session_dirs() -> list[Path]:
    """Every project dir that can hold session logs: live first, then the archive."""
    dirs: list[Path] = []
    for root in (CLAUDE_PROJECTS_DIR, CLAUDE_ARCHIVE_DIR):
        if root.is_dir():
            dirs.extend(d for d in sorted(root.iterdir()) if d.is_dir())
    return dirs


def _project_matches(proj_dir: Path, project: str) -> bool:
    """True if proj_dir is the Claude Code dir for the --project path or basename."""
    wanted = project.rstrip("/")
    return (proj_dir.name == os.path.basename(wanted)
            or proj_dir.name.endswith(wanted.replace("/", "-"))
            or wanted.replace("/", "-").lstrip("-") in proj_dir.name)


def _load_all_index_entries() -> dict[str, dict]:
    """sessionId -> sessions-index.json entry, from every index in the live and archive dirs.

    Naming metadata only. Keeps transcripts that were named from an index stable after their
    log moves to the archive (the index file itself is never moved)."""
    meta: dict[str, dict] = {}
    for d in _session_dirs():
        for e in load_sessions_index(d):
            if e.get("sessionId"):
                meta.setdefault(e["sessionId"], e)
    return meta


def _existing_transcripts(output_dir: Path) -> dict[str, list[Path]]:
    """sessionId -> transcript files already written for it (read from frontmatter)."""
    found: dict[str, list[Path]] = {}
    for t in output_dir.glob("*.md"):
        if t.name == INDEX_FILE.name:
            continue
        with open(t, "r", encoding="utf-8", errors="replace") as f:
            head = f.read(600)
        m = re.search(r"^session_id:\s*(\S+)", head, re.MULTILINE)
        if m:
            found.setdefault(m.group(1), []).append(t)
    return found


def _build_entry(jsonl_path: Path, sid: str, indexed: Optional[dict]) -> dict:
    """Build the naming/metadata entry for a session from its own log.

    Reads the start timestamp, the most-used working directory, the first real user prompt and the
    latest /rename title (custom-title records). Values from a sessions-index.json entry,
    when one exists, win so previously written transcript names do not change."""
    created = first_prompt = title = ""
    cwds: dict[str, int] = {}
    with open(jsonl_path, "r", encoding="utf-8", errors="replace") as f:
        for raw in f:
            try:
                obj = json.loads(raw)
            except json.JSONDecodeError:
                continue
            kind = obj.get("type", "")
            if kind == "custom-title" and obj.get("customTitle"):
                title = obj["customTitle"]
                continue
            if obj.get("isSidechain"):
                continue
            if not created and isinstance(obj.get("timestamp"), str):
                created = obj["timestamp"]
            if obj.get("cwd"):
                cwds[obj["cwd"]] = cwds.get(obj["cwd"], 0) + 1
            if not first_prompt and kind == "user" and not obj.get("isMeta"):
                text = _extract_user_text(obj.get("message") or {})
                if text:
                    first_prompt = text[:200]
    # Sessions often start in my-lib and then work in a project; label by where most of it ran.
    cwd = max(cwds, key=cwds.get) if cwds else ""
    entry = {
        "sessionId": sid,
        "fullPath": str(jsonl_path),
        "firstPrompt": first_prompt,
        "summary": title,
        "created": created,
        "projectPath": cwd or str(jsonl_path.parent),
    }
    if indexed:
        for key in ("firstPrompt", "summary", "created", "projectPath"):
            if indexed.get(key):
                entry[key] = indexed[key]
    return entry


def run(
    days: Optional[int] = None,
    project: Optional[str] = None,
    session_id: Optional[str] = None,
    force: bool = False,
    verbose: bool = False,
) -> dict:
    """
    Main extraction runner. Returns summary stats dict.

    Args:
        days: Only process sessions from the last N days.
        project: Limit to a specific project path (basename or full path).
        session_id: Limit to a single session ID.
        force: Re-extract even if transcript is up-to-date.
        verbose: Print detailed progress.
    """
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # Session discovery lists the JSONL files themselves, in the live projects dir AND the
    # archive. sessions-index.json is used only as naming metadata: Claude Code stopped
    # maintaining it (the my-lib pool's copy froze on 2026-04-02), and trusting it as the
    # session list silently skipped every session created after that date.
    project_dirs = [d for d in _session_dirs() if not project or _project_matches(d, project)]
    index_meta = _load_all_index_entries()
    existing = _existing_transcripts(OUTPUT_DIR)          # sid -> [transcript paths]
    owner = {p.name: sid for sid, ps in existing.items() for p in ps}  # filename -> sid

    # --days filters on the log's last-modified time: the start date is not known until the
    # log is read, and a session touched recently is the one whose transcript may be stale.
    cutoff_ts: Optional[float] = None
    if days:
        cutoff_ts = (datetime.now(timezone.utc) - timedelta(days=days)).timestamp()

    stats = {
        "processed": 0,
        "renamed": 0,
        "skipped_uptodate": 0,
        "skipped_no_content": 0,
        "errors": 0,
        "missing": [],
        "total_input_bytes": 0,
        "total_output_bytes": 0,
    }
    considered: set[str] = set()  # sessions that passed the filters this run
    covered: set[str] = set()     # sessions that have a transcript or legitimately have none

    # One session id can exist as two different log files (a copy left in an old project dir
    # when sessions moved to the shared pool). Keep the largest: it is the most complete.
    candidates: dict[str, Path] = {}
    for proj_dir in project_dirs:
        if verbose:
            print(f"\nProject dir: {proj_dir}")
        for jsonl_path in proj_dir.glob("*.jsonl"):
            if jsonl_path.name.startswith("agent-"):
                continue
            real = jsonl_path.resolve()
            prev = candidates.get(jsonl_path.stem)
            if prev is None or real.stat().st_size > prev.stat().st_size:
                candidates[jsonl_path.stem] = real

    for sid, real in sorted(candidates.items()):
        if session_id and sid != session_id:
            continue
        jsonl_mtime = real.stat().st_mtime
        if cutoff_ts and jsonl_mtime < cutoff_ts:
            continue
        input_size = real.stat().st_size
        considered.add(sid)

        olds = existing.get(sid, [])
        if (not force and olds
                and all(p.stat().st_mtime >= jsonl_mtime for p in olds)
                and not any(p.name.startswith("000000-") for p in olds)):
            stats["skipped_uptodate"] += 1
            covered.add(sid)
            if verbose:
                print(f"  SKIP (up-to-date): {olds[0].name}")
            continue

        if verbose:
            print(f"  Processing: {sid[:12]}... ({input_size:,} bytes)")
        # One unreadable log must not stop the rest; it is counted and reported as missing.
        try:
            entry = _build_entry(real, sid, index_meta.get(sid))
            result = process_session(real, entry, verbose=verbose)
        except Exception as e:
            print(f"  ERROR reading {real}: {e}", file=sys.stderr)
            stats["errors"] += 1
            continue
        if result is None:
            stats["skipped_no_content"] += 1
            covered.add(sid)
            continue

        # Two sessions can derive the same name (same title or same first words).
        name = result["filename"]
        if owner.get(name, sid) != sid:
            name = f"{name[:-3]}-{sid[:8]}.md"
        final_out_path = OUTPUT_DIR / name
        try:
            with open(final_out_path, "w", encoding="utf-8") as f:
                f.write(result["content"])
        except OSError as e:
            print(f"  ERROR writing {final_out_path}: {e}", file=sys.stderr)
            stats["errors"] += 1
            continue
        owner[name] = sid
        covered.add(sid)
        # A changed name (fixed date prefix, later /rename) replaces the old file.
        for p in olds:
            if p != final_out_path and p.exists():
                p.unlink()
                owner.pop(p.name, None)
                stats["renamed"] += 1
                if verbose:
                    print(f"  RENAMED: {p.name} -> {name}")
        output_size = final_out_path.stat().st_size
        stats["processed"] += 1
        stats["total_input_bytes"] += input_size
        stats["total_output_bytes"] += output_size
        if verbose:
            ratio = output_size / input_size * 100 if input_size else 0
            print(f"  WROTE: {name} ({output_size:,} bytes, {ratio:.1f}% of input)")

    # Completeness check: every session considered this run must now have a transcript,
    # or have been read and found to hold no conversation. A job that only reports
    # "Errors: 0" proves it ran, not that it covered everything.
    stats["missing"] = sorted(considered - covered)

    # Rebuild index
    try:
        _rebuild_index(OUTPUT_DIR, INDEX_FILE)
    except OSError as e:
        print(f"  ERROR rebuilding {INDEX_FILE}: {e}", file=sys.stderr)
        stats["errors"] += 1

    return stats


