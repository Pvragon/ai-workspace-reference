# Breadcrumb builder
# ---------------------------------------------------------------------------

def _build_breadcrumb(tool_calls: list[dict]) -> Optional[str]:
    """
    Build a compact breadcrumb string from a list of tool calls in a single turn.

    Format: > [Read: a.md, b.md | Edit: c.md | Bash: 2 commands]
    """
    if not tool_calls:
        return None

    # Group by tool type
    read_files: list[str] = []
    edit_files: list[str] = []
    write_files: list[str] = []
    notebook_files: list[str] = []
    bash_count = 0
    grep_count = 0
    grep_first: Optional[str] = None
    glob_count = 0
    glob_first: Optional[str] = None
    web_search_count = 0
    web_search_first: Optional[str] = None
    web_fetch_count = 0
    web_fetch_first: Optional[str] = None
    task_descriptions: list[str] = []
    skill_names: list[str] = []
    task_create_count = 0
    task_update_count = 0
    task_list_count = 0
    other: dict[str, int] = {}  # tool_name -> count

    for tc in tool_calls:
        name = tc.get("name", "")
        inp = tc.get("input", {}) or {}

        if name == "Read":
            fp = inp.get("file_path", "")
            if fp:
                read_files.append(os.path.basename(fp) if len(fp) > 40 else fp)
        elif name in ("Edit", "MultiEdit"):
            fp = inp.get("file_path", "")
            if fp:
                edit_files.append(os.path.basename(fp) if len(fp) > 40 else fp)
        elif name == "Write":
            fp = inp.get("file_path", "")
            if fp:
                write_files.append(os.path.basename(fp) if len(fp) > 40 else fp)
        elif name == "NotebookEdit":
            fp = inp.get("notebook_path", "")
            if fp:
                notebook_files.append(os.path.basename(fp) if len(fp) > 40 else fp)
        elif name == "Bash":
            bash_count += 1
        elif name in ("Grep", "GlobSearch"):
            if name == "Grep":
                grep_count += 1
                if grep_first is None:
                    q = inp.get("pattern", inp.get("query", ""))
                    if q and len(q) < 50:
                        grep_first = q
            else:
                glob_count += 1
                if glob_first is None:
                    q = inp.get("pattern", "")
                    if q and len(q) < 50:
                        glob_first = q
        elif name == "WebSearch":
            web_search_count += 1
            if web_search_first is None:
                q = inp.get("query", "")
                if q and len(q) < 60:
                    web_search_first = q
        elif name == "WebFetch":
            web_fetch_count += 1
            if web_fetch_first is None:
                url = inp.get("url", "")
                if url and len(url) < 60:
                    web_fetch_first = url
        elif name in ("Task", "Agent"):
            desc = inp.get("description", inp.get("prompt", ""))
            if desc:
                task_descriptions.append(str(desc)[:60])
        elif name == "Skill":
            skill_name = inp.get("skill", "")
            if skill_name:
                skill_names.append(skill_name)
        elif name in ("TaskCreate", "mcp__clickup__create_task"):
            task_create_count += 1
        elif name in ("TaskUpdate", "mcp__clickup__update_task"):
            task_update_count += 1
        elif name in ("TaskList", "mcp__clickup__get_tasks"):
            task_list_count += 1
        else:
            # Any other MCP or tool
            other[name] = other.get(name, 0) + 1

    parts = []

    if read_files:
        parts.append(f"Read: {', '.join(read_files[:5])}" + (f" +{len(read_files)-5}" if len(read_files) > 5 else ""))
    if edit_files:
        parts.append(f"Edit: {', '.join(edit_files[:5])}" + (f" +{len(edit_files)-5}" if len(edit_files) > 5 else ""))
    if write_files:
        parts.append(f"Write: {', '.join(write_files[:5])}" + (f" +{len(write_files)-5}" if len(write_files) > 5 else ""))
    if notebook_files:
        parts.append(f"NotebookEdit: {', '.join(notebook_files[:3])}")
    if bash_count:
        parts.append(f"Bash: {bash_count} command{'s' if bash_count > 1 else ''}")
    if grep_count:
        parts.append(f"Grep: {grep_count}" + (f" ('{grep_first}')" if grep_first else ""))
    if glob_count:
        parts.append(f"Glob: {glob_count}" + (f" ('{glob_first}')" if glob_first else ""))
    if web_search_count:
        parts.append(f"WebSearch: {web_search_count}" + (f" ('{web_search_first}')" if web_search_first else ""))
    if web_fetch_count:
        parts.append(f"WebFetch: {web_fetch_count}" + (f" ('{web_fetch_first}')" if web_fetch_first else ""))
    for desc in task_descriptions[:2]:
        parts.append(f"Task: {desc}")
    for sn in skill_names[:2]:
        parts.append(f"Skill: {sn}")
    if task_create_count:
        parts.append(f"TaskCreate: {task_create_count}")
    if task_update_count:
        parts.append(f"TaskUpdate: {task_update_count}")
    if task_list_count:
        parts.append(f"TaskList: {task_list_count}")
    for tool_name, count in other.items():
        # Abbreviate long MCP tool names
        short_name = tool_name.split("__")[-1] if "__" in tool_name else tool_name
        parts.append(f"{short_name}: {count}")

    if not parts:
        return None

    return f"> [{' | '.join(parts)}]"


