#!/usr/bin/env python3
# ---
# template: execution
# version: 1.0.1
# summary: Generate the `## Contents` table of a directory's index.md from the `summary:` of each
#          file the registry indexes, per config/registry-map.yaml. Third consumer of
#          build_registry.read_frontmatter. Default is a rebuild-and-diff check; --apply writes.
# created: 2026-08-08
# last_updated: 2026-08-08
# maintainer: pvragon
# known_limitations: >-
#   Regenerates ONLY the body of the `## Contents` section. Any other line in that section is
#   treated as hand-authored and the write is REFUSED rather than overwritten. Reads `summary:`
#   only — a file carrying just `description:` is reported as having no pointer field, never
#   silently substituted, because two candidate fields is two owners for one row.
# ---
"""An index.md is a BUILD ARTIFACT below its `## Contents` heading, and a document above it.

`progressive-disclosure-convention.md` says an index file should aggregate its siblings' summaries
into a discovery table so an agent can assess a whole directory in one read. Every index.md in the
workspace instead carried the sentence "See `registry/X.yaml` for the current file manifest" —
a pointer written when the only alternative was a hand-maintained listing that would drift.

Generation removes the drift, so the choice is no longer between a stale table and no table. The
prose sections a human wrote (Purpose / What Belongs Here / naming conventions) are preserved
byte-for-byte; only the table is owned by this tool, and it is owned by exactly one field —
the indexed file's own `summary:`, which is the same field the registry manifest derives from.
"""
from __future__ import annotations

import argparse
import difflib
import os
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
# POINTER_FIELDS is IMPORTED, not restated. The index and the manifest must never disagree about
# which frontmatter field describes a file, and two copies of that list is exactly how they would.
from build_registry import (POINTER_FIELDS, discover, pointer,  # noqa: E402  (same directory)
                            provenance, read_frontmatter)

MARKER = (
    "<!-- GENERATED by team-lib/executions/build_index.py from each file's `summary:` — do not\n"
    "     hand-edit. To change a row, edit the `summary:` in the file that row names. -->"
)
HEADING = "## Contents"
WILDCARD = re.compile(r"[*?\[]")
POINTER = re.compile(r"^See\b.*registry/[\w.-]+\.ya?ml", re.I)


# ---------------------------------------------------------------------------- where the index goes
class IndexTargetConflict(Exception):
    """The spec's globs live in more than one directory, so 'the' index is not defined."""


def index_target(repo: Path, spec: dict) -> Path | None:
    """The index.md this registry spec describes, or None when the spec opts out.

    Derived from the STATIC prefix of each glob, not declared, because a declaration is a second
    copy of where the files already are. But it is derived only when the answer is unambiguous:
    acme-health-main's `skills` spec globs both `skills/` and `.claude/skills/`, and there is no
    honest way to pick one — so it raises and the caller reports it rather than guessing and
    writing a table into whichever directory sorted first.
    """
    declared = spec.get("index")
    if declared is False:
        return None
    if isinstance(declared, str):
        return repo / declared
    dirs = set()
    for g in spec["globs"]:
        parts = []
        for part in Path(g).parts:
            if WILDCARD.search(part):
                break
            parts.append(part)
        dirs.add(Path(*parts) if parts else Path("."))
    if len(dirs) != 1:
        raise IndexTargetConflict(
            f"globs span {len(dirs)} directories ({', '.join(sorted(str(d) for d in dirs))}) — "
            f"declare `index: <path/to/index.md>` (or `index: false`) in the spec")
    return repo / dirs.pop() / "index.md"


# ---------------------------------------------------------------------------- the guard
def _replaceable(line: str) -> bool:
    """Is this a line THIS TOOL could have written?

    The refusal analog of build_registry's comments-below guard. A `## Contents` section that
    holds anything else holds something a human put there, and overwriting it is the one
    irreversible thing this tool could do.
    """
    s = line.strip()
    return (not s
            or s.startswith("|")
            or s.startswith("<!--") or s.endswith("-->") or s.startswith("hand-edit.")
            or bool(POINTER.match(s))
            or (s.startswith("_") and s.endswith("_")))


def split_contents(text: str) -> tuple[str, str, str] | None:
    """(before, contents-body, after) around the `## Contents` section, or None if absent."""
    lines = text.splitlines(keepends=True)
    start = next((i for i, ln in enumerate(lines) if ln.strip() == HEADING), None)
    if start is None:
        return None
    end = next((j for j in range(start + 1, len(lines)) if lines[j].startswith("## ")), len(lines))
    return "".join(lines[:start]), "".join(lines[start + 1:end]), "".join(lines[end:])


# ---------------------------------------------------------------------------- render
def _cell(value: str) -> str:
    """One table cell: whitespace collapsed, pipes escaped so a summary cannot break the table."""
    return " ".join(str(value).split()).replace("|", "\\|")


def render_contents(repo: Path, idx: Path, spec: dict, found: dict[str, Path],
                    budget: int) -> tuple[str, dict]:
    """The generated `## Contents` body, plus what was wrong with the files it read."""
    fields = spec.get("pointer_fields") or POINTER_FIELDS
    report = {"no_summary": [], "malformed": [], "budget": [], "budget_external": [],
              "fallback": []}
    rows = []
    for eid in sorted(found):
        p = found[eid]
        rel = os.path.relpath(p, idx.parent)
        fm = read_frontmatter(p)
        used, value = pointer(fm, fields)
        if not isinstance(fm, dict):
            bucket = "malformed" if str(fm).startswith("malformed") else "no_summary"
            report[bucket].append(f"{eid} ({p.relative_to(repo)})")
            cell = ("_frontmatter present but will not parse_" if bucket == "malformed"
                    else "_no frontmatter_")
        elif used is None:
            # ⚑ Reported AND still listed. Dropping the row would make the index narrower than the
            # directory it indexes, which reads as coverage — the exact failure the summary gap is.
            report["no_summary"].append(f"{eid} ({p.relative_to(repo)})")
            cell = f"_no {' or '.join(f'`{f}:`' for f in fields)} in the file_"
        else:
            if used != fields[0]:
                report["fallback"].append(f"{eid}: no `{fields[0]}:`, used `{used}:` "
                                          f"({p.relative_to(repo)})")
            cell = _cell(value)
            words = len(cell.split())
            if words > budget:
                # A third-party file under `_external/` must not be modified, so reporting it as a
                # fixable defect would be a permanent finding nobody is allowed to close. Split by
                # RESOLVED provenance, the same discriminator build_registry uses for `source:`.
                bucket = ("budget_external" if provenance(repo, p) == "external" else "budget")
                report[bucket].append(f"{eid}: {words}w (budget {budget}) — shorten the "
                                      f"`{used}:` in {p.relative_to(repo)}")
        rows.append(f"| [`{eid}`]({rel}) | {cell} |")

    manifest = os.path.relpath(repo / spec["file"], idx.parent)
    body = ["", MARKER, ""]
    if rows:
        body += ["| Name | Summary |", "|------|---------|", *rows]
    else:
        body += ["_No indexed files in this directory._"]
    body += ["", f"See [`{spec['file']}`]({manifest}) for the full manifest.", ""]
    return "\n".join(body) + "\n", report


def build_one(repo: Path, name: str, spec: dict, budget: int) -> dict:
    """Everything about one index: what it should say, whether it may be written, and why not."""
    out = {"name": name, "path": None, "raw": "", "rendered": "", "refused": None,
           "created": False, "error": None,
           "report": {"no_summary": [], "malformed": [], "budget": [], "budget_external": [],
                      "fallback": [], "collision": []}}
    try:
        idx = index_target(repo, spec)
    except IndexTargetConflict as exc:
        out["error"] = str(exc)
        return out
    if idx is None:
        return out
    out["path"] = idx

    found, collisions = discover(repo, spec)
    contents, rep = render_contents(repo, idx, spec, found, budget)
    out["report"] = dict(rep, collision=collisions)

    raw = idx.read_text(encoding="utf-8") if idx.exists() else ""
    out["raw"] = raw
    parts = split_contents(raw)
    if parts is None:
        # No `## Contents` yet. Append one rather than inventing a whole document — a directory
        # README is a human's to write, and a file that is only a generated table says nothing
        # about what belongs in the folder.
        head = raw if raw.endswith("\n") or not raw else raw + "\n"
        if not head.strip():
            head = f"# {idx.parent.name}\n"
            out["created"] = True
        out["rendered"] = head.rstrip("\n") + "\n\n" + HEADING + "\n" + contents
        return out

    before, body, after = parts
    bad = [ln for ln in body.splitlines() if not _replaceable(ln)]
    if bad:
        out["refused"] = bad
    out["rendered"] = before + HEADING + "\n" + contents + after
    return out


# ---------------------------------------------------------------------------- cli
def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo", default=os.getcwd())
    ap.add_argument("--config", default=None)
    ap.add_argument("--only", help="one registry name from the map")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--force", action="store_true",
                    help="write even over hand-authored lines inside `## Contents`")
    ap.add_argument("--self-check", action="store_true")
    a = ap.parse_args(argv)
    if a.self_check:
        return self_check()

    repo = Path(a.repo).resolve()
    cfg = yaml.safe_load(Path(a.config or repo / "config" / "registry-map.yaml").read_text())
    budget = int(cfg.get("summary_budget_words", 60))
    rc = 0
    for name, spec in cfg["registries"].items():
        if a.only and name != a.only:
            continue
        r = build_one(repo, name, spec, budget)
        print(f"\n── {name}")
        if r["error"]:
            print(f"   ⚑ no index target: {r['error']}")
            rc = max(rc, 2)
            continue
        if r["path"] is None:
            print("   declared `index: false` — skipped")
            continue
        print(f"   {r['path'].relative_to(repo)}")
        for k, label in (("no_summary", "no pointer field — row shows a placeholder"),
                         ("malformed", "⚑ MALFORMED frontmatter — will not parse"),
                         ("budget", "OVER BUDGET — fix in the file"),
                         ("budget_external", "ℹ over budget in `_external/` — must not be modified"),
                         ("fallback", "ℹ no `summary:`, fell back to `description:`"),
                         ("collision", "⚑ ID COLLISION — two files claim one row, one DROPPED")):
            if r["report"][k]:
                print(f"   {label}: {len(r['report'][k])}")
                for x in r["report"][k][:6]:
                    print(f"      - {x}")
        if r["raw"] == r["rendered"]:
            print("   clean")
            continue
        if not a.apply:
            d = list(difflib.unified_diff(r["raw"].splitlines(), r["rendered"].splitlines(),
                                          "current", "generated", lineterm="", n=0))
            n = sum(1 for x in d if x[:1] in "+-" and x[:3] not in ("---", "+++"))
            print(f"   rebuild-and-diff: {n} line(s) differ"
                  + ("  (index.md would be CREATED)" if r["created"] else ""))
            rc = max(rc, 1)
            continue
        if r["refused"] and not a.force:
            print("   REFUSING to write — `## Contents` holds lines this tool did not generate:")
            for ln in r["refused"][:6]:
                print(f"      | {ln.rstrip()}")
            print("   Move them to their own section, or re-run with --force to discard them.")
            rc = max(rc, 2)
            continue
        r["path"].parent.mkdir(parents=True, exist_ok=True)
        r["path"].write_text(r["rendered"], encoding="utf-8")
        print(f"   wrote {r['path'].relative_to(repo)}")
    return rc


# ---------------------------------------------------------------------------- self-check
def self_check() -> int:
    """Two-sided, and every guard is MUTATION-TESTED: each assertion below has been checked to
    FAIL when the behaviour it names is removed. A guard nobody falsified is an untested claim."""
    import tempfile
    ok = True

    def fail(msg):
        nonlocal ok
        print(f"FAIL: {msg}")
        ok = False

    with tempfile.TemporaryDirectory() as td:
        repo = Path(td)
        (repo / "executions").mkdir()
        (repo / "registry").mkdir()
        (repo / "executions" / "alpha.py").write_text(
            "#!/usr/bin/env python3\n# ---\n# summary: Does the alpha thing.\n# ---\n")
        (repo / "executions" / "beta.py").write_text(
            "#!/usr/bin/env python3\n# ---\n# summary: Pipes | in | a | summary.\n# ---\n")
        (repo / "executions" / "gamma.py").write_text(
            "#!/usr/bin/env python3\n# ---\n# description: only a description, no summary\n# ---\n")
        (repo / "executions" / "delta.py").write_text("print('no frontmatter at all')\n")
        (repo / "registry" / "executions.yaml").write_text("executions: {}\n")
        spec = {"file": "registry/executions.yaml", "key": "executions", "shape": "map",
                "globs": ["executions/*.py"], "field": "description",
                "derived": ["path", "description"]}
        # a real map on disk, so the CLI-level assertions below exercise main() end to end
        # rather than only the library function
        (repo / "config").mkdir()
        (repo / "config" / "registry-map.yaml").write_text(yaml.safe_dump(
            {"summary_budget_words": 60, "registries": {"executions": spec}}))
        prose = ("# executions\n\n## Purpose\nHand-written prose that must survive.\n\n"
                 "## Contents\n\nSee `registry/executions.yaml` for the current file manifest.\n\n"
                 "## How Agents Should Use This Folder\nAlso hand-written.\n")
        idx = repo / "executions" / "index.md"
        idx.write_text(prose)

        r = build_one(repo, "executions", spec, 60)
        if r["refused"]:
            fail(f"the stock 'See registry/...' pointer was treated as hand-authored: {r['refused']}")
        idx.write_text(r["rendered"])
        got = idx.read_text()

        # every file gets a row — including the ones with no summary and no frontmatter
        for eid in ("alpha", "beta", "gamma", "delta"):
            if f"[`{eid}`]" not in got:
                fail(f"{eid} is on disk but has no row — the index is narrower than the directory")
        # `description:` is used when `summary:` is absent, and the substitution is REPORTED
        if "only a description, no summary" not in got:
            fail("`description:` was not used as a fallback when `summary:` was absent")
        if "gamma" not in " ".join(r["report"]["fallback"]):
            fail("the fallback to `description:` was silent — the summary gap became invisible")
        if "gamma" in " ".join(r["report"]["no_summary"]):
            fail("a file WITH `description:` was reported as having no pointer field")
        if "delta" not in " ".join(r["report"]["no_summary"]):
            fail("a file with no frontmatter at all was not reported")
        if "_no frontmatter_" not in got:
            fail("the no-frontmatter row did not say so — a blank cell reads as 'nothing to say'")

        # hand-authored prose OUTSIDE the section survives byte-for-byte
        for keep in ("Hand-written prose that must survive.", "## How Agents Should Use This Folder",
                     "Also hand-written."):
            if keep not in got:
                fail(f"hand-authored content was destroyed: {keep!r}")

        # a pipe in a summary must not break the table: every row has exactly 2 data cells
        for line in got.splitlines():
            if line.startswith("| [`"):
                if len(re.findall(r"(?<!\\)\|", line)) != 3:
                    fail(f"unescaped pipe broke a table row: {line}")

        # regeneration is a no-op
        r2 = build_one(repo, "executions", spec, 60)
        if r2["raw"] != r2["rendered"]:
            fail("regenerating a clean index is not a no-op")

        # over budget is REPORTED, and never trimmed in the index
        (repo / "executions" / "alpha.py").write_text(
            "#!/usr/bin/env python3\n# ---\n# summary: " + "word " * 80 + "\n# ---\n")
        r3 = build_one(repo, "executions", spec, 60)
        if not r3["report"]["budget"]:
            fail("an over-budget summary was not reported")
        if "word word" not in r3["rendered"]:
            fail("the index trimmed a long summary instead of reporting it — that is a 2nd owner")

        # THE GUARD: a hand-authored line inside `## Contents` must refuse
        idx.write_text(r2["rendered"].replace(
            "See [`registry/executions.yaml`]",
            "Note: this paragraph was written by a person.\n\nSee [`registry/executions.yaml`]"))
        r4 = build_one(repo, "executions", spec, 60)
        if not r4["refused"]:
            fail("a hand-authored line inside `## Contents` was silently overwritable")
        if main(["--repo", str(repo), "--apply"]) != 2:
            fail("--apply did not exit 2 on a refusal")
        if "written by a person" not in idx.read_text():
            fail("a refused write happened anyway")
        if main(["--repo", str(repo), "--apply", "--force"]) != 0:
            fail("--force did not override the refusal")

        # `## Contents` absent entirely -> appended, nothing else touched
        idx.write_text("# executions\n\n## Purpose\nOnly prose here.\n")
        r5 = build_one(repo, "executions", spec, 60)
        if HEADING not in r5["rendered"] or "Only prose here." not in r5["rendered"]:
            fail("a missing `## Contents` was not appended alongside the existing prose")

        # index.md absent entirely -> created with a title
        idx.unlink()
        r6 = build_one(repo, "executions", spec, 60)
        if not r6["created"] or not r6["rendered"].startswith("# executions"):
            fail("a missing index.md was not created with a heading")

        # an over-budget THIRD-PARTY file is informational, not a fixable defect: we are forbidden
        # to edit `_external/`, so filing it as actionable creates a finding nobody may close
        (repo / "skills" / "_external" / "pack" / "vendored").mkdir(parents=True)
        (repo / "skills" / "_external" / "pack" / "vendored" / "SKILL.md").write_text(
            "---\ndescription: " + "word " * 80 + "\n---\n")
        (repo / "skills" / "mine").mkdir(parents=True)
        (repo / "skills" / "mine" / "SKILL.md").write_text(
            "---\nsummary: " + "word " * 80 + "\n---\n")
        sk = {"file": "registry/skills.yaml", "globs": ["skills/**/SKILL.md"],
              "field": "description", "derived": ["path", "description"]}
        r9 = build_one(repo, "skills", sk, 60)
        if "vendored" not in " ".join(r9["report"]["budget_external"]):
            fail("an over-budget `_external/` file was not classed as unfixable")
        if "vendored" in " ".join(r9["report"]["budget"]):
            fail("an `_external/` file was filed as a fixable over-budget defect")
        if "mine" not in " ".join(r9["report"]["budget"]):
            fail("an over-budget file WE own was not filed as fixable")

        # ambiguous globs must RAISE, never guess a directory
        r7 = build_one(repo, "executions",
                       dict(spec, globs=["executions/*.py", "other/*.py"]), 60)
        if not r7["error"]:
            fail("globs spanning two directories picked one instead of reporting the ambiguity")

        # and an explicit declaration resolves it
        r8 = build_one(repo, "executions",
                       dict(spec, globs=["executions/*.py", "other/*.py"],
                            index="executions/index.md"), 60)
        if r8["error"] or r8["path"] != repo / "executions" / "index.md":
            fail("an explicit `index:` did not resolve the ambiguity")

    print("self-check: PASS" if ok else "self-check: FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
